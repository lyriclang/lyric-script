#!/usr/bin/env python3
"""Generates the value-probe programs (Lyric-Script design round, area 11: a VM written in Lyric 5).

    python3 gen.py <outdir>

W1  w1_coerce.lyr   what a value costs on its way into an interface value: a class instance, a
                    string, a small struct, an int; plus the move of a ready interface value and
                    the store of a plain class reference as baselines. One program, the mode from
                    argv[1].
W2  w2_<layout>.lyr the register VM of the dispatch probe (48 opcodes, same Instr, same match),
                    its frame holding scalars AND references, in five layouts:
                      a     split files: scalars: uint64[] + refs: HeapRef[]
                      b     one file of two-word slots Value { bits: uint64, ref: HeapRef },
                            a shared NilRef object for "no reference"; a scalar write writes .bits
                      bc    as b, but a scalar write writes the whole slot (ref = the nil object)
                      o     slots Value { bits: uint64, ref: ?HeapRef }; a scalar write writes .bits
                      oc    as o, a scalar write writes the whole slot (ref = null)
    w2_p0.c         the same computation as a plain C loop: the oracle for acc.
W3  w3_map.lyr      an open-addressing table over string keys, looked up 10^7 times; key hashing
                    and equality called on the concrete type (mono), through the key's own
                    interface table (iface), or through a separate witness object over HeapRef
                    keys (wit). One program, the mode from argv[1].

Every program prints `key=value` pairs; run.py checks them against what each must print.
"""
