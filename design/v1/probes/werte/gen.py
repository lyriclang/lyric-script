W3_HEAD = r'''// GENERATED by gen.py — W3: string-keyed lookups, the key's hash and equality called on the
// concrete type (mono), through the key's interface table (iface), or through a witness object
// over HeapRef keys (wit). Value probe (lyric-script design round, area 11). See README.md.
//   w3_map <mode> <keys> <queries, a power of two> <lookups>
// Prints mode, ns (the lookup loop, in-process), allocs (the loop's allocations: 0 expected) and
// check = sum of the found values + hits * 2^32.
import std.io { println };
import std.os { args };
import std.core { arrayOf, Hasher };
import std.time { Monotonic };

extern "C" fn lyr_gc_thread_allocations(): int;

/// A cheap word-at-a-time hasher (FxHash's step, a splitmix finisher), so that hashing does not
/// hide what the call around it costs. std's string hashing feeds it eight bytes at a time.
struct Fx :: [Hasher] {
    var h: uint64,
    mut fn writeByte(b: uint8): void {
        this.h = (((this.h << 5) | (this.h >> 59)) ^ (b as uint64)) *% 0x517CC1B727220A95;
    }
    mut fn writeUint(v: uint64): void {
        this.h = (((this.h << 5) | (this.h >> 59)) ^ v) *% 0x517CC1B727220A95;
    }
    fn finish(): uint64 {
        var x = this.h;
        x = x ^ (x >> 29);
        x = x *% 0xBF58476D1CE4E5B9;
        x = x ^ (x >> 32);
        return x;
    }
}

fn hashStr(s: string): uint64 {
    var fx = Fx { h = 0 };
    s.hash(&fx);
    return fx.finish();
}

interface HeapRef {
    fn kind(): int;
}

/// The key's own table: what a shared instance calls on a K that is an interface value.
interface KeyRef {
    fn keyHash(): uint64;
    fn keyEquals(o: KeyRef): bool;
}

extend string :: [HeapRef, KeyRef] {
    fn kind(): int { return 2; }
    fn keyHash(): uint64 { return hashStr(this); }
    fn keyEquals(o: KeyRef): bool {
        if (o is string) { return this == o; }
        return false;
    }
}

/// A second conformer of each interface, so that no call can be bound to the one implementation.
class IntKey :: [HeapRef, KeyRef] {
    v: int,
    fn kind(): int { return 3; }
    fn keyHash(): uint64 { return (this.v as uint64) *% 0x9E3779B97F4A7C15; }
    fn keyEquals(o: KeyRef): bool {
        if (o is IntKey) { return this.v == o.v; }
        return false;
    }
}

/// The witness: hashing and equality of one key type, apart from the keys (Swift's witness
/// table, .NET's EqualityComparer<T>.Default), over keys that are HeapRef values.
interface KeyWitness {
    fn hash(k: HeapRef): uint64;
    fn eq(a: HeapRef, b: HeapRef): bool;
}

class StringWitness :: [KeyWitness] {
    fn hash(k: HeapRef): uint64 {
        if (k is string) { return hashStr(k); }
        panic("not a string");
    }
    fn eq(a: HeapRef, b: HeapRef): bool {
        if (a is string) {
            if (b is string) { return a == b; }
        }
        return false;
    }
}

class IntWitness :: [KeyWitness] {
    fn hash(k: HeapRef): uint64 {
        if (k is IntKey) { return (k.v as uint64) *% 0x9E3779B97F4A7C15; }
        panic("not an IntKey");
    }
    fn eq(a: HeapRef, b: HeapRef): bool {
        if (a is IntKey) {
            if (b is IntKey) { return a.v == b.v; }
        }
        return false;
    }
}

/// A string behind an object of its own, called directly (mode mbox): the box without the dispatch.
class StrBox {
    s: string,
}

fn asKeyRef(s: string): KeyRef {
    return s;
}

fn asHeapRef(s: string): HeapRef {
    return s;
}
'''

W3_TABLE = r'''
class Table%VC% {
    keys: %K%[],
    hashes: uint64[],
    vals: int[],
    mask: int,
    wit: KeyWitness,
}

fn insert%VC%(t: Table%VC%, k: %K%, v: int): void {
    let h = %HASH(k)% | 1;
    var slot = (h & (t.mask as uint64)) as int;
    while (t.hashes[slot] != 0) {
        slot = (slot + 1) & t.mask;
    }
    t.hashes[slot] = h;
    t.keys[slot] = k;
    t.vals[slot] = v;
}

fn lookup%VC%(t: Table%VC%, k: %K%): int {
    let h = %HASH(k)% | 1;
    var slot = (h & (t.mask as uint64)) as int;
    while (true) {
        let sh = t.hashes[slot];
        if (sh == 0) {
            return -1;
        }
        if (sh == h) {
            if (%EQ(t.keys[slot], k)%) {
                return t.vals[slot];
            }
        }
        slot = (slot + 1) & t.mask;
    }
}

@NoInline
fn bench%VC%(t: Table%VC%, queries: %K%[], lookups: int): int {
    let qmask = queries.length() - 1;
    var sum = 0;
    var hits = 0;
    var i = 0;
    while (i < lookups) {
        let r = lookup%VC%(t, queries[i & qmask]);
        if (r >= 0) {
            sum += r;
            hits += 1;
        }
        i += 1;
    }
    return sum + hits * 4294967296;
}
'''

W3_VARIANTS = {
    'mono': dict(K='string', HASH='hashStr({k})', EQ='{a} == {b}'),
    # direct calls, but every key behind one more object, as a box puts it: splits iface's cost
    # into the indirection and the dispatch
    'mbox': dict(K='StrBox', HASH='hashStr({k}.s)', EQ='{a}.s == {b}.s'),
    'iface': dict(K='KeyRef', HASH='{k}.keyHash()', EQ='{a}.keyEquals({b})'),
    'wit': dict(K='HeapRef', HASH='t.wit.hash({k})', EQ='t.wit.eq({a}, {b})'),
}

W3_MAIN = r'''
/// The hash alone, over the same queries: what of a lookup is hashing (mode "hash").
@NoInline
fn benchHash(queries: string[], lookups: int): int {
    let qmask = queries.length() - 1;
    var sum = 0;
    var i = 0;
    while (i < lookups) {
        sum += (hashStr(queries[i & qmask]) & 0xFFFF) as int;
        i += 1;
    }
    return sum;
}

fn main(): int {
    let argv = args();
    let mode = argv[1];
    let n = (try? int.parse(argv[2])) ?? 1000000;
    let q = (try? int.parse(argv[3])) ?? 1048576;
    let lookups = (try? int.parse(argv[4])) ?? 10000000;
    var cap = 1;
    while (cap < 2 * n) {
        cap = cap * 2;
    }
    let keyStrs: string[] = arrayOf(n, (i: int) => f"key{i}");
    let queryStrs: string[] = arrayOf(q, (j: int) => if ((j & 3) == 3) f"miss{j}" else f"key{(j * 7919) % n}");
    let stringWitness: KeyWitness = StringWitness {};
    let intWitness: KeyWitness = IntWitness {};
    // the second conformers exist and are called once, so they stay in the program
    let other: KeyRef = IntKey { v = 7 };
    let otherRef: HeapRef = IntKey { v = 7 };
    let sideCheck = (other.keyHash() & 1) as int + (intWitness.hash(otherRef) & 1) as int + otherRef.kind();

    var check = 0;
    var ns = 0;
    var allocs = 0;
    if (mode == "mono") {
        let t = TableMono { keys = [""] * cap, hashes = [0u64] * cap, vals = [0] * cap, mask = cap - 1, wit = stringWitness };
        var i = 0;
        while (i < n) {
            insertMono(t, keyStrs[i], i);
            i += 1;
        }
        let a0 = lyr_gc_thread_allocations();
        let t0 = Monotonic.now();
        check = benchMono(t, queryStrs, lookups);
        ns = t0.elapsed().nanos();
        allocs = lyr_gc_thread_allocations() - a0;
    } else if (mode == "mbox") {
        let emptyBox = StrBox { s = "" };
        let t = TableMbox { keys = arrayOf(cap, (i: int) => emptyBox), hashes = [0u64] * cap, vals = [0] * cap, mask = cap - 1, wit = stringWitness };
        var i = 0;
        while (i < n) {
            insertMbox(t, StrBox { s = keyStrs[i] }, i);
            i += 1;
        }
        let queries: StrBox[] = arrayOf(q, (j: int) => StrBox { s = queryStrs[j] });
        let a0 = lyr_gc_thread_allocations();
        let t0 = Monotonic.now();
        check = benchMbox(t, queries, lookups);
        ns = t0.elapsed().nanos();
        allocs = lyr_gc_thread_allocations() - a0;
    } else if (mode == "iface") {
        let empty: KeyRef = "";
        let t = TableIface { keys = arrayOf(cap, (i: int) => empty), hashes = [0u64] * cap, vals = [0] * cap, mask = cap - 1, wit = stringWitness };
        var i = 0;
        while (i < n) {
            insertIface(t, asKeyRef(keyStrs[i]), i);
            i += 1;
        }
        let queries: KeyRef[] = arrayOf(q, (j: int) => asKeyRef(queryStrs[j]));
        let a0 = lyr_gc_thread_allocations();
        let t0 = Monotonic.now();
        check = benchIface(t, queries, lookups);
        ns = t0.elapsed().nanos();
        allocs = lyr_gc_thread_allocations() - a0;
    } else if (mode == "wit") {
        let empty: HeapRef = "";
        let t = TableWit { keys = arrayOf(cap, (i: int) => empty), hashes = [0u64] * cap, vals = [0] * cap, mask = cap - 1, wit = stringWitness };
        var i = 0;
        while (i < n) {
            insertWit(t, asHeapRef(keyStrs[i]), i);
            i += 1;
        }
        let queries: HeapRef[] = arrayOf(q, (j: int) => asHeapRef(queryStrs[j]));
        let a0 = lyr_gc_thread_allocations();
        let t0 = Monotonic.now();
        check = benchWit(t, queries, lookups);
        ns = t0.elapsed().nanos();
        allocs = lyr_gc_thread_allocations() - a0;
    } else if (mode == "hash") {
        let a0 = lyr_gc_thread_allocations();
        let t0 = Monotonic.now();
        check = benchHash(queryStrs, lookups);
        ns = t0.elapsed().nanos();
        allocs = lyr_gc_thread_allocations() - a0;
    } else {
        panic("unknown mode");
    }
    println(f"mode={mode} n={n} q={q} lookups={lookups} cap={cap} ns={ns} allocs={allocs} check={check} side={sideCheck}");
    return 0;
}
'''

def w3_lyric():
    out = W3_HEAD
    for v, d in W3_VARIANTS.items():
        t = W3_TABLE.replace('%VC%', v.capitalize()).replace('%K%', d['K'])
        t = t.replace('%HASH(k)%', d['HASH'].format(k='k'))
        t = t.replace('%EQ(t.keys[slot], k)%', d['EQ'].format(a='t.keys[slot]', b='k'))
        out += t
    return out + W3_MAIN

# =============================================================================================== main

def main():
    out = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.')
